# Checking Descriptive Stats using ordereddict function

from collections import OrderedDict
stats = []

for i in numerical_data.columns:
  numerical_stats = OrderedDict({
      'Feature':i,
      'Skewness':numerical_data[i].skew(),
      'Kurtosis':numerical_data[i].kurt(),
      'Mean':numerical_data[i].mean(),
      'Median':numerical_data[i].median(),
      'Mode':numerical_data[i].mode()[0],
      'Standard Deviation':numerical_data[i].std(),
      'Variance':numerical_data[i].var(),
      'Minimum':numerical_data[i].min(),
      'Maximum':numerical_data[i].max(),
      'Range':numerical_data[i].max()-numerical_data[i].min(),
      'IQR':numerical_data[i].quantile(0.75)-numerical_data[i].quantile(0.25),
      '1.5 IQR':1.5*(numerical_data[i].quantile(0.75)-numerical_data[i].quantile(0.25)),
      'Lower Fence':numerical_data[i].quantile(0.25)-1.5*(numerical_data[i].quantile(0.75)-numerical_data[i].quantile(0.25)),
      'Upper Fence':numerical_data[i].quantile(0.75)+1.5*(numerical_data[i].quantile(0.75)-numerical_data[i].quantile(0.25))


  })
  stats.append(numerical_stats)
stats_df = pd.DataFrame(stats)
